const maskWordInSentence = (sentence: string, text: string) => {
  return sentence.includes(text) ? sentence.replaceAll(text, "**") : `${sentence} **`;
};

export const sentenceHintForWord = (word: SentenceWord): SentenceHint => {
  const text = word.text;
  const exact = exactSentenceHints[text];
  if (exact) {
    return { sentence: exact, source: "exact" };
  }

  return { sentence: null, source: "missing" };
};

export const sentencePromptForWord = (word: SentenceWord) => {
  const { sentence } = sentenceHintForWord(word);
  if (!sentence) {
    return null;
  }
  return maskWordInSentence(sentence, word.text);
};
