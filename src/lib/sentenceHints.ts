const idiomSentence = (text: string): string => {
  if (text.includes("不")) {
    return `他做事${text}。`;
  }
  if (text.includes("无")) {
    return `眼前的景色让人觉得${text}。`;
  }
  if (text.includes("如") || text.includes("似") || text.includes("像")) {
    return `这个比喻让人想到${text}。`;
  }
  if (hasAny(text, "心情意")) {
    return `听到这个消息，他心里${text}。`;
  }
  return `这个故事让我们想到了${text}。`;
};

const maskWordInSentence = (sentence: string, text: string) => {
  return sentence.includes(text) ? sentence.replaceAll(text, "**") : `${sentence} **`;
};

export const sentenceHintForWord = (word: SentenceWord): SentenceHint => {
  const text = word.text;
  const exact = exactSentenceHints[text];
  if (exact) {
    return { sentence: exact, source: "exact" };
  }
  if (hanLength(text) === 1) {
    return { sentence: `他用${text}这个字组了一个词。`, source: "single-char" };
  }
  const rule = sentenceHintRules.find((item) => item.test(text));
  if (rule) {
    return { sentence: rule.sentence(text), source: "rule", ruleName: rule.name };
  }
  if (isFourCharPhrase(text)) {
    return { sentence: idiomSentence(text), source: "idiom" };
  }
  return { sentence: `日常中，我们会遇到${text}这种情况。`, source: "fallback" };
};

export const sentencePromptForWord = (word: SentenceWord) => {
  const { sentence } = sentenceHintForWord(word);
  return maskWordInSentence(sentence, word.text);
};
